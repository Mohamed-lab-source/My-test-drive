// The same name all day, moving through the list one name per day.
export function nameOfTheDay(now: Date = new Date()): DivineName {
  const day = Math.floor(new Date(now.getFullYear(), now.getMonth(), now.getDate()).getTime() / 86400000);
  return NAMES[((day % 99) + 99) % 99];
}
